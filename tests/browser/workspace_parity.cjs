// Run against a disposable local practice/simulated radio server only.
const {chromium}=require("playwright");
(async()=>{
 const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
 const page=await browser.newPage({viewport:{width:1366,height:768}});
 const errors=[];page.on("pageerror",e=>errors.push(e.message));
 await page.goto("http://127.0.0.1:8765/");
 await page.locator("#welcome-dialog[open]").waitFor();
 await page.locator('[data-onboard="observer"]').click();
 await page.locator("#settings-dialog[open]").waitFor();
 if(!await page.locator('[name="observer_mode"]').isChecked())throw Error("observer choice not applied");
 if(await page.locator('[name="kiss_port"]').isVisible())throw Error("advanced controls visible");
 await page.locator("#advanced-radio").click();
 if(!await page.locator('[name="kiss_port"]').isVisible())throw Error("advanced not expanded");
 await page.locator("#settings-cancel").click();
 await page.getByRole("button",{name:"Play offline instead",exact:true}).click();
 await page.waitForFunction(()=>state.snapshot?.ready&&state.snapshot?.transport==="practice");
 const cards=page.locator("#arena-body .game-library-card");
 await cards.first().waitFor();
 if(await page.locator(".station-panel").isVisible())throw Error("practice chat should be collapsed");
 const word=cards.filter({hasText:"Open Word Tiles"});
 await word.getByRole("button",{name:"Play vs computer"}).click();
 await page.waitForSelector(".word-rack-interactive");
 const tile=page.locator('.word-rack-interactive button:not(:disabled)').filter({hasNotText:"?"}).first();
 const letter=await tile.textContent();
 await tile.dragTo(page.locator('.word-cell[data-index="112"]'));
 if(await page.locator("#word-text").inputValue()!==letter)throw Error("rack drag did not compose");
 await page.locator("#focus-toggle").click();
 if(await page.locator(".lobby-panel").isVisible())throw Error("focus did not hide lobby");
 await page.locator("#focus-toggle").click();
 await page.locator("#chat-toggle").click();
 if(!await page.locator(".station-panel").isVisible())throw Error("chat did not restore");
 await page.locator("#new-game").click();
 await page.locator("#library-dialog[open]").waitFor();
 await page.locator("#library-dialog .game-library-card").filter({hasText:"Battleship Classic"}).getByRole("button",{name:"Play vs computer"}).click();
 await page.waitForSelector(".bs-placement-grid");
 await page.getByRole("button",{name:"Randomize",exact:true}).click();
 if(!await page.getByRole("button",{name:"Deploy fleet"}).isEnabled())throw Error("fleet not ready");
 await page.locator("#session-actions summary").click();
 if(!await page.getByRole("button",{name:"Forfeit game…",exact:true}).isVisible())throw Error("contextual actions missing");
 if(await page.getByRole("button",{name:/Resync table/}).count())throw Error("practice recovery action");
 // Narrow browser retains its section navigation.
 await page.setViewportSize({width:390,height:780});
 await page.locator('.mobile-tab[data-pane="lobby"]').click();
 await page.locator("#new-game").click();await page.locator("#library-dialog[open]").waitFor();
 await page.locator('[data-close-dialog="library-dialog"]').click();
 if(errors.length)throw Error(errors.join("\n"));
 console.log("PASS: first run, advanced settings, game library, practice, drag, focus, chat, fleet, table menu, mobile");
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
